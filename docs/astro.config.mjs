const ensureDirectiveAttributes = (node) => {
  if (!node || typeof node !== 'object') return;
  if (typeof node.type === 'string' && node.type.endsWith('Directive') && !node.attributes) {
    node.attributes = {};
  }
  if (Array.isArray(node.children)) {
    for (const child of node.children) ensureDirectiveAttributes(child);
  }
};
